#!/usr/bin/env node
'use strict';
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),crypto=require('node:crypto');
const root=path.join(__dirname,'../games');
const sha256=value=>crypto.createHash('sha256').update(value).digest('hex');
function build(){
  const context=vm.createContext({window:{}});
  vm.runInContext(fs.readFileSync(path.join(root,'shared/arcade-catalog.js'),'utf8'),context);
  const games=context.window.ArcadeCatalog.games;
  const files=new Set(),queue=['index.html',...games.map(game=>game.href+'index.html')];
  function local(source,reference){
    if(!reference||/^(?:data:|#)/i.test(reference))return null;
    if(/^(?:[a-z]+:|\/)/i.test(reference))throw Error(`${source}: offline game assets must use local relative URLs (${reference})`);
    const clean=reference.split(/[?#]/)[0],result=path.posix.normalize(path.posix.join(path.posix.dirname(source),clean));
    if(result.startsWith('../')||!fs.existsSync(path.join(root,result))||!fs.statSync(path.join(root,result)).isFile())throw Error(`${source}: missing offline asset ${reference}`);
    return result;
  }
  function add(source,reference){const file=local(source,reference);if(file&&!files.has(file))queue.push(file);}
  function attribute(tag,name){return tag.match(new RegExp(`\\b${name}\\s*=\\s*["']([^"']+)["']`,'i'))?.[1];}
  while(queue.length){
    const file=queue.shift();if(files.has(file))continue;
    files.add(file);const content=fs.readFileSync(path.join(root,file),'utf8');
    if(file.endsWith('.html')){
      for(const match of content.matchAll(/<(script|link|img|source)\b[^>]*>/gi)){
        const tag=match[0],type=match[1].toLowerCase();
        if(type==='script'||type==='img'||type==='source')add(file,attribute(tag,'src'));
        else if(/(?:stylesheet|icon|preload)/i.test(attribute(tag,'rel')||''))add(file,attribute(tag,'href'));
      }
    }else if(file.endsWith('.css')){
      for(const match of content.matchAll(/url\(\s*["']?([^\s"')]+)["']?\s*\)/g))add(file,match[1]);
    }else if(file.endsWith('.js')){
      for(const match of content.matchAll(/\b(?:importScripts|new\s+Worker)\(\s*["']([^"']+)["']/g))add(file,match[1]);
    }
  }
  const assets=[...files].sort().map(file=>({path:file,sha256:sha256(fs.readFileSync(path.join(root,file)))}));
  const version='v1-'+sha256(JSON.stringify(assets)+['games-sw.js','legacy-routes.js','root-migration.js'].map(file=>fs.readFileSync(path.join(root,file),'utf8')).join('\n')).slice(0,20);
  return {version,gameCount:games.length,assets};
}
function source(){return '/* Generated by node scripts/build-offline-cache.cjs. Do not edit by hand. */\nself.ARCADE_OFFLINE_MANIFEST = '+JSON.stringify(build(),null,2)+';\n';}
if(require.main===module){
  const file=path.join(root,'offline-assets.js'),expected=source();
  if(process.argv.includes('--check')){
    if(!fs.existsSync(file)||fs.readFileSync(file,'utf8')!==expected){console.error('Offline assets are stale. Run: node scripts/build-offline-cache.cjs');process.exitCode=1;}
    else console.log('Offline release manifest is current.');
  }else{fs.writeFileSync(file,expected);const data=build();console.log(`Prepared ${data.assets.length} files for ${data.gameCount} games (${data.version}).`);}
}
module.exports={build,source};
